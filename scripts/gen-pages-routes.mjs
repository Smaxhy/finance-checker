// Generates the route files for the GitHub Pages edition: every server page under
// src/app/(app) gets a static shell (page.local.tsx) that runs the same page in the
// browser against on-device data. Output is git-ignored; run before `next build`.
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "../src/app/(app)");

async function* walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(p);
    else if (entry.name === "page.tsx") yield p;
  }
}

let count = 0;
for await (const file of walk(root)) {
  const dir = path.dirname(file);
  const source = await readFile(file, "utf8");
  const dynamic = path.basename(dir).match(/^\[(\w+)\]$/)?.[1];
  const hasMetadata = /export const metadata\b/.test(source);
  const header = "// Generated by scripts/gen-pages-routes.mjs for the GitHub Pages edition - do not edit.\n";
  await writeFile(
    path.join(dir, "page-client.local.tsx"),
    `"use client";\n${header}import Page from "./page";\nimport { LocalPage } from "@/lib/local/runtime";\n\nexport default function PageClient() {\n  return <LocalPage page={Page}${dynamic ? ` dynamicParam="${dynamic}"` : ""} />;\n}\n`,
  );
  await writeFile(
    path.join(dir, "page.local.tsx"),
    `${header}import { Suspense } from "react";\nimport { PageSkeleton } from "@/lib/local/runtime";\nimport PageClient from "./page-client.local";\n${hasMetadata ? 'export { metadata } from "./page";\n' : ""}${
      dynamic ? `\nexport const dynamicParams = false;\nexport function generateStaticParams() {\n  return [{ ${dynamic}: "_" }];\n}\n` : ""
    }\nexport default function LocalRoute() {\n  return (\n    <Suspense fallback={<PageSkeleton />}>\n      <PageClient />\n    </Suspense>\n  );\n}\n`,
  );
  count++;
}
console.log(`Generated ${count} GitHub Pages routes`);
